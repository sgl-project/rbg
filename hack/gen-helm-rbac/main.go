// Command gen-helm-rbac renders the Helm chart's ClusterRole template from the
// controller-gen output in config/rbac/role.yaml.
//
// The chart cannot simply copy that file because it needs the chart-scoped
// ClusterRole name. Rendering it here also prevents the generated RBAC from drifting
// as kubebuilder markers change.
package main

import (
	"errors"
	"fmt"
	"os"
	"strings"

	rbacv1 "k8s.io/api/rbac/v1"
	"sigs.k8s.io/yaml"
)

const (
	sourcePath = "config/rbac/role.yaml"
	targetPath = "deploy/helm/rbgs/templates/rbac/clusterrole.yaml"
	// chartRoleName is the chart-scoped name; controller-gen emits "controller-role".
	chartRoleName = "rbgs-controller-role"
)

// fileHeader is emitted verbatim. The toggle is read exactly as
// deploy/helm/rbgs/templates/manager/manager.yaml reads it, so the RBAC granted here
// and the manager's --enable-deprecated-workload-types flag cannot disagree.
const fileHeader = `---
{{- /*
  Generated by hack/gen-helm-rbac from config/rbac/role.yaml; DO NOT EDIT.
  Run "make manifests" after changing kubebuilder RBAC markers.
*/}}
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: ` + chartRoleName + `
rules:
`

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen-helm-rbac: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := os.ReadFile(sourcePath)
	if err != nil {
		return fmt.Errorf("read %s: %w", sourcePath, err)
	}

	role, err := parseRole(raw)
	if err != nil {
		return fmt.Errorf("%s: %w", sourcePath, err)
	}

	blocks := make([]ruleBlock, 0, len(role.Rules))
	for _, rule := range role.Rules {
		if len(rule.Resources) > 0 {
			blocks = append(blocks, ruleBlock{rule: rule})
		}
	}
	out, err := render(blocks)
	if err != nil {
		return err
	}
	if err := os.WriteFile(targetPath, out, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", targetPath, err)
	}
	fmt.Printf("gen-helm-rbac: wrote %s from %s\n", targetPath, sourcePath)
	return nil
}

// parseRole decodes controller-gen's output. It is strict about both the schema and
// the kind: a misspelled key such as "resource:" for "resources:" would otherwise
// leave that rule empty and drop it from the output silently, and a "kind: Role"
// document would be rendered as the chart's ClusterRole.
func parseRole(raw []byte) (*rbacv1.ClusterRole, error) {
	var role rbacv1.ClusterRole
	if err := yaml.UnmarshalStrict(raw, &role); err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	if role.Kind != "ClusterRole" {
		return nil, fmt.Errorf("declares kind %q, want ClusterRole", role.Kind)
	}
	if len(role.Rules) == 0 {
		return nil, errors.New("declares no rules")
	}
	return &role, nil
}

// ruleBlock is a policy rule rendered by the Helm chart generator.
type ruleBlock struct {
	rule rbacv1.PolicyRule
}

// render serialises the blocks into the chart template.
func render(blocks []ruleBlock) ([]byte, error) {
	var sb strings.Builder
	sb.WriteString(fileHeader)

	for _, block := range blocks {
		encoded, err := yaml.Marshal([]rbacv1.PolicyRule{block.rule})
		if err != nil {
			return nil, fmt.Errorf("marshal rule: %w", err)
		}
		sb.Write(encoded)
	}
	return []byte(sb.String()), nil
}
